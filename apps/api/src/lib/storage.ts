/**
 * Storage abstraction for uploaded media files.
 *
 * SaaS upgrade path:
 *   - Swap LocalDiskStorage for an S3Storage or R2Storage implementation
 *   - No changes needed in routes or adapters — they only call upload() / getBuffer()
 *   - When auth lands, pass userId into upload() to scope paths per user
 *
 * Bluesky limits (most restrictive — good baseline for all platforms):
 *   - Max 4 images per post
 *   - Max 1 MB per image
 *   - Accepted types: image/jpeg, image/png, image/gif, image/webp
 */

import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { S3Client, PutObjectCommand, GetObjectCommand, DeleteObjectCommand, ListObjectsV2Command } from "@aws-sdk/client-s3";

export const ALLOWED_IMAGE_TYPES = ["image/jpeg", "image/png", "image/gif", "image/webp"];
export const MAX_IMAGE_SIZE_BYTES = 10_000_000; // 10 MB
export const MAX_IMAGES_PER_POST = 4;

const EXT_MAP: Record<string, string> = {
  "image/jpeg": ".jpg",
  "image/png": ".png",
  "image/gif": ".gif",
  "image/webp": ".webp",
  "video/mp4": ".mp4",
  "video/quicktime": ".mov",
  "video/mov": ".mov",
  "application/x-figma": ".fig",
};

/** Filesystem- and URL-safe version of a user-supplied file name (keeps the extension). */
export function safeFileName(name: string): string {
  const ext = path.extname(name).replace(/[^\w.]/g, "").slice(0, 10);
  const base = path.basename(name, path.extname(name))
    .normalize("NFKD")
    .replace(/[^\w.-]+/g, "-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "")
    .slice(0, 100);
  return `${base || "file"}${ext}`;
}

/** `<folder>/<uuid><ext>`, or `<folder>/<uuid>/<name>` when the original file name should survive download. */
function objectKey(mimeType: string, folder?: string, fileName?: string): string {
  const id = crypto.randomUUID();
  const name = fileName ? `${id}/${safeFileName(fileName)}` : `${id}${EXT_MAP[mimeType] ?? ".bin"}`;
  return folder ? `${folder}/${name}` : name;
}

export interface StorageAdapter {
  /**
   * Persist a file and return a URL the client and job runner can use.
   * Pass fileName to keep it as the last URL segment (readable download name).
   */
  upload(buffer: Buffer, mimeType: string, folder?: string, fileName?: string): Promise<string>;

  /** Read a file back as a Buffer so adapters can upload it to platforms. */
  getBuffer(url: string): Promise<Buffer>;

  /** Delete a stored file by its URL. Called after a job posts successfully. */
  delete(url: string): Promise<void>;

  /** List all public URLs of files stored in a given folder. */
  listFolder(folder: string): Promise<string[]>;

  /** Returns true if this URL was generated by this storage adapter. */
  ownsUrl(url: string): boolean;
}

/** A key or URL that does not name a file inside the uploads folder. Nothing was read, written or removed. */
export class StorageKeyError extends Error {
  readonly code = "EINVALIDKEY";
  constructor() {
    super("That is not a path inside the uploads folder.");
    this.name = "StorageKeyError";
  }
}

export class LocalDiskStorage implements StorageAdapter {
  constructor(private readonly uploadsDir: string) {}

  /**
   * Where a key lives on disk, or a StorageKeyError. Every read, write, delete and listing goes through here:
   *  - the key is cut into segments and none may be empty, "." or "..", or contain a backslash, a colon (a drive or stream on Windows) or
   *    a NUL: nothing is ever resolved by joining text that came from outside;
   *  - the result must still lie under the REAL path of the uploads folder;
   *  - no part of the key may be a symbolic link (the app never makes one), so a link planted in the folder cannot lead out of it.
   * shortcut: a link swapped in between this check and the file operation is not caught; that needs write access to the uploads folder,
   * which is the same access the files themselves are protected by. Upgrade: open with O_NOFOLLOW (not available on Windows).
   */
  private async locate(key: string): Promise<string> {
    if (typeof key !== "string" || !key) throw new StorageKeyError();
    const segments = key.split("/");
    if (segments.some((s) => s === "" || s === "." || s === ".." || /[\\:\0]/.test(s))) throw new StorageKeyError();
    const resolved = path.resolve(this.uploadsDir);
    const root = await fs.realpath(resolved).catch((err: NodeJS.ErrnoException) => {
      if (err.code === "ENOENT") return resolved; // nothing has been stored yet
      throw err;
    });
    const full = path.resolve(root, ...segments);
    if (!full.startsWith(root + path.sep)) throw new StorageKeyError();
    let at = root;
    for (const segment of segments) {
      at = path.join(at, segment);
      try {
        if ((await fs.lstat(at)).isSymbolicLink()) throw new StorageKeyError();
      } catch (err) {
        if (err instanceof StorageKeyError) throw err;
        const code = (err as NodeJS.ErrnoException).code;
        if (code === "ENOENT" || code === "ENOTDIR") break; // the rest of the path does not exist yet
        throw err;
      }
    }
    return full;
  }

  /** The key of an "/uploads/..." URL. Anything else is not ours. */
  private keyOf(url: string): string {
    if (typeof url !== "string" || !url.startsWith("/uploads/")) throw new StorageKeyError();
    return url.slice("/uploads/".length);
  }

  async upload(buffer: Buffer, mimeType: string, folder?: string, fileName?: string): Promise<string> {
    const key = objectKey(mimeType, folder, fileName);
    const filepath = await this.locate(key);
    await fs.mkdir(path.dirname(filepath), { recursive: true });
    await fs.writeFile(filepath, buffer);
    return `/uploads/${key}`;
  }

  async getBuffer(url: string): Promise<Buffer> {
    // Support both /uploads/filename and /uploads/folder/filename
    return fs.readFile(await this.locate(this.keyOf(url)));
  }

  async delete(url: string): Promise<void> {
    const filepath = await this.locate(this.keyOf(url));
    try {
      await fs.unlink(filepath);
    } catch (err: unknown) {
      // File already gone — not an error
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
    }
  }

  async listFolder(folder: string): Promise<string[]> {
    const dir = await this.locate(folder);
    try {
      const files = await fs.readdir(dir);
      return files.map((f) => `/uploads/${folder}/${f}`);
    } catch {
      return [];
    }
  }

  ownsUrl(url: string): boolean {
    return url.startsWith("/uploads/");
  }
}

/**
 * SupabaseStorage — swap in when AUTH_PROVIDER=supabase.
 * Uses the Supabase Storage API (S3-compatible bucket).
 *
 * Set env vars:
 *   SUPABASE_URL, SUPABASE_SERVICE_KEY, SUPABASE_STORAGE_BUCKET (default: "uploads")
 */
export class SupabaseStorage implements StorageAdapter {
  private readonly bucket: string;
  private readonly baseUrl: string;
  private readonly serviceKey: string;

  constructor() {
    const url = process.env.SUPABASE_URL;
    const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
    if (!url || !key) throw new Error("SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required for SupabaseStorage");
    this.baseUrl = url;
    this.serviceKey = key;
    this.bucket = process.env.SUPABASE_STORAGE_BUCKET ?? "uploads";
  }

  private storageUrl(path: string) {
    return `${this.baseUrl}/storage/v1/object/${this.bucket}/${path}`;
  }

  private headers() {
    return { Authorization: `Bearer ${this.serviceKey}`, apikey: this.serviceKey };
  }

  async upload(buffer: Buffer, mimeType: string, folder?: string, fileName?: string): Promise<string> {
    const filename = objectKey(mimeType, folder, fileName);
    const res = await fetch(this.storageUrl(filename), {
      method: "POST",
      headers: { ...this.headers(), "Content-Type": mimeType },
      body: new Uint8Array(buffer),
    });
    if (!res.ok) throw new Error(`Supabase upload failed: ${await res.text()}`);
    return `${this.baseUrl}/storage/v1/object/public/${this.bucket}/${filename}`;
  }

  async getBuffer(url: string): Promise<Buffer> {
    // The service key goes with this request: it must never be sent to an address that is not this project's storage.
    if (!this.ownsUrl(url)) throw new StorageKeyError();
    const res = await fetch(url, { headers: this.headers(), redirect: "error" });
    if (!res.ok) throw new Error(`Supabase getBuffer failed: ${res.status}`);
    return Buffer.from(await res.arrayBuffer());
  }

  async delete(url: string): Promise<void> {
    // Extract the path after /object/public/{bucket}/
    const marker = `/object/public/${this.bucket}/`;
    const idx = url.indexOf(marker);
    const filePath = idx !== -1 ? url.slice(idx + marker.length) : url.split("/").pop()!;
    const res = await fetch(`${this.baseUrl}/storage/v1/object/${this.bucket}/${filePath}`, {
      method: "DELETE",
      headers: this.headers(),
    });
    if (!res.ok && res.status !== 404) throw new Error(`Supabase delete failed: ${await res.text()}`);
  }

  async listFolder(folder: string): Promise<string[]> {
    const res = await fetch(`${this.baseUrl}/storage/v1/object/list/${this.bucket}`, {
      method: "POST",
      headers: { ...this.headers(), "Content-Type": "application/json" },
      body: JSON.stringify({ prefix: `${folder}/`, limit: 1000, offset: 0 }),
    });
    if (!res.ok) return [];
    const items = await res.json() as Array<{ name: string }>;
    return items.map((f) => `${this.baseUrl}/storage/v1/object/public/${this.bucket}/${folder}/${f.name}`);
  }

  ownsUrl(url: string): boolean {
    return url.startsWith(`${this.baseUrl}/`); // with the slash: https://project.supabase.co.evil.test/ is not this project
  }
}

/**
 * R2Storage — Cloudflare R2 via S3-compatible API. Zero egress fees.
 *
 * Set env vars:
 *   R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY,
 *   R2_BUCKET (default: "posthive-uploads"), R2_PUBLIC_URL (public dev URL)
 */
export class R2Storage implements StorageAdapter {
  private readonly client: S3Client;
  private readonly bucket: string;
  private readonly publicUrl: string;

  constructor() {
    const accountId = process.env.R2_ACCOUNT_ID;
    const accessKeyId = process.env.R2_ACCESS_KEY_ID;
    const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY;
    const publicUrl = process.env.R2_PUBLIC_URL;
    if (!accountId || !accessKeyId || !secretAccessKey || !publicUrl) {
      throw new Error("R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_PUBLIC_URL are required for R2Storage");
    }
    this.bucket = process.env.R2_BUCKET ?? "posthive-uploads";
    this.publicUrl = publicUrl.replace(/\/$/, "");
    this.client = new S3Client({
      region: "auto",
      endpoint: `https://${accountId}.r2.cloudflarestorage.com`,
      credentials: { accessKeyId, secretAccessKey },
      forcePathStyle: true,
    });
  }

  async upload(buffer: Buffer, mimeType: string, folder?: string, fileName?: string): Promise<string> {
    const key = objectKey(mimeType, folder, fileName);
    await this.client.send(new PutObjectCommand({
      Bucket: this.bucket,
      Key: key,
      Body: new Uint8Array(buffer),
      ContentType: mimeType,
    }));
    return `${this.publicUrl}/${key}`;
  }

  async getBuffer(url: string): Promise<Buffer> {
    const key = url.replace(`${this.publicUrl}/`, "");
    const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if (!res.Body) throw new Error(`R2 getBuffer: empty body for ${key}`);
    return Buffer.from(await res.Body.transformToByteArray());
  }

  async delete(url: string): Promise<void> {
    const key = url.replace(`${this.publicUrl}/`, "");
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  async listFolder(folder: string): Promise<string[]> {
    const res = await this.client.send(new ListObjectsV2Command({
      Bucket: this.bucket,
      Prefix: `${folder}/`,
      MaxKeys: 1000,
    }));
    return (res.Contents ?? []).map((obj) => `${this.publicUrl}/${obj.Key}`);
  }

  ownsUrl(url: string): boolean {
    return url.startsWith(`${this.publicUrl}/`); // with the slash: https://pub.r2.dev.evil.test/ is not this bucket
  }
}
